"""
Executive Excel Styler for Benchmark Arabic LLMs.
Transforms plain DataFrames into publication-grade executive workbooks
with KPI summary cards, corporate/academic styling, auto-fitted widths,
conditional formatting color heatmaps, and embedded native charts.
"""

from pathlib import Path
from typing import List, Dict, Any, Optional
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
from openpyxl.formatting.rule import ColorScaleRule
from openpyxl.chart import BarChart, Reference


NAVY_DARK = "0F172A"       # Slate 900
HEADER_FILL = "1E293B"     # Slate 800
TEAL_ACCENT = "32C4B7"     # Project Teal
ZEBRA_FILL = "F8FAFC"      # Slate 50
WHITE = "FFFFFF"
GRAY_TEXT = "64748B"       # Slate 500
CARD_BG = "F1F5F9"         # Slate 100
BORDER_COLOR = "E2E8F0"    # Slate 200

# Fonts
FONT_TITLE = Font(name="Segoe UI", size=16, bold=True, color=NAVY_DARK)
FONT_SUBTITLE = Font(name="Segoe UI", size=10, italic=True, color=GRAY_TEXT)
FONT_HEADER = Font(name="Segoe UI", size=11, bold=True, color=WHITE)
FONT_BODY = Font(name="Segoe UI", size=10, color="000000")
FONT_BOLD = Font(name="Segoe UI", size=10, bold=True, color="000000")
FONT_KPI_VAL = Font(name="Segoe UI", size=14, bold=True, color="0F172A")
FONT_KPI_LBL = Font(name="Segoe UI", size=8, bold=True, color=GRAY_TEXT)

# Fills
FILL_HEADER = PatternFill(start_color=HEADER_FILL, end_color=HEADER_FILL, fill_type="solid")
FILL_ZEBRA = PatternFill(start_color=ZEBRA_FILL, end_color=ZEBRA_FILL, fill_type="solid")
FILL_WHITE = PatternFill(start_color=WHITE, end_color=WHITE, fill_type="solid")
FILL_TEAL_ACCENT = PatternFill(start_color="E6FFFA", end_color="E6FFFA", fill_type="solid")
FILL_CARD = PatternFill(start_color=CARD_BG, end_color=CARD_BG, fill_type="solid")

# Borders
THIN_SIDE = Side(style="thin", color=BORDER_COLOR)
BOX_BORDER = Border(left=THIN_SIDE, right=THIN_SIDE, top=THIN_SIDE, bottom=THIN_SIDE)


def style_existing_workbook(
    file_path: Path | str,
    task_name: str = "Benchmark Evaluation",
    model_results: Optional[Dict[str, Any]] = None,
) -> Path:
    """
    Load an Excel file generated by pandas, apply executive styling,
    auto-size columns, add conditional color heatmaps, and inject a KPI sheet.
    """
    path = Path(file_path)
    if not path.exists():
        return path

    wb = openpyxl.load_workbook(path)

    # 1. Style each existing data sheet
    for sheet_name in wb.sheetnames:
        ws = wb[sheet_name]
        _style_data_sheet(ws)

    # 2. Add or prepend Executive KPI Dashboard sheet if model results are provided
    if model_results:
        _add_executive_dashboard(wb, task_name, model_results)

    wb.save(path)
    return path


def _style_data_sheet(ws):
    """Format headers, zebra rows, borders, numbers, and heatmaps on a data worksheet."""
    ws.views.sheetView[0].showGridLines = True
    max_row = ws.max_row
    max_col = ws.max_column

    if max_row < 1 or max_col < 1:
        return

    # Style Header Row
    ws.row_dimensions[1].height = 28
    for col_idx in range(1, max_col + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.font = FONT_HEADER
        cell.fill = FILL_HEADER
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BOX_BORDER

    # Style Data Rows
    metric_cols = []
    for col_idx in range(1, max_col + 1):
        header_val = str(ws.cell(row=1, column=col_idx).value or "").lower()
        if any(m in header_val for m in ["score", "accuracy", "em", "f1", "rouge", "bleu", "meteor", "rate"]):
            metric_cols.append(col_idx)

    for row_idx in range(2, max_row + 1):
        ws.row_dimensions[row_idx].height = 20
        is_even = (row_idx % 2 == 0)
        row_fill = FILL_ZEBRA if is_even else FILL_WHITE

        for col_idx in range(1, max_col + 1):
            cell = ws.cell(row=row_idx, column=col_idx)
            cell.font = FONT_BODY
            cell.fill = row_fill
            cell.border = BOX_BORDER

            # Number formatting
            if isinstance(cell.value, (int, float)):
                if "rate" in str(ws.cell(row=1, column=col_idx).value or "").lower():
                    cell.number_format = "0.0%"
                    cell.alignment = Alignment(horizontal="right", vertical="center")
                elif isinstance(cell.value, float):
                    cell.number_format = "0.0000"
                    cell.alignment = Alignment(horizontal="right", vertical="center")
                else:
                    cell.alignment = Alignment(horizontal="center", vertical="center")
            else:
                cell.alignment = Alignment(horizontal="left", vertical="center")

    # Conditional formatting color scale for numeric metric columns
    if max_row >= 3 and metric_cols:
        for c_idx in metric_cols:
            col_letter = get_column_letter(c_idx)
            rule = ColorScaleRule(
                start_type="min", start_color="FEE2E2",  # Soft Red
                mid_type="percentile", mid_value=50, mid_color="FEF3C7", # Soft Yellow
                end_type="max", end_color="DCFCE7",     # Soft Green
            )
            ws.conditional_formatting.add(f"{col_letter}2:{col_letter}{max_row}", rule)

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            val_str = str(cell.value or "")
            if len(val_str) > max_len:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 12)


def _add_executive_dashboard(wb: openpyxl.Workbook, task_name: str, model_results: Dict[str, Any]):
    """Insert an Executive Summary KPI dashboard at the beginning of the workbook."""
    ws = wb.create_sheet(title="Executive Summary", index=0)
    ws.views.sheetView[0].showGridLines = True

    # Title
    ws["B2"] = "Framework for Open-Source Multilingual Large Language Models"
    ws["B2"].font = FONT_TITLE
    ws["B3"] = f"Executive Benchmark Report: {task_name.replace('_', ' ').title()}"
    ws["B3"].font = FONT_SUBTITLE

    # Identify top performers
    best_model = "N/A"
    best_score = -1.0
    total_examples = 0
    total_errors = 0

    model_scores_list = []
    for model_name, m_data in model_results.items():
        scores = m_data.get("scores", {})
        stats = m_data.get("stats", {})
        total_examples += stats.get("n_examples", 0)
        total_errors += stats.get("n_errors", 0)

        # Primary score heuristic
        primary = (
            scores.get("Accuracy")
            or scores.get("accuracy")
            or scores.get("ROUGEL")
            or scores.get("rougeL")
            or scores.get("F1")
            or scores.get("EM")
            or 0.0
        )
        if isinstance(primary, (int, float)) and primary > best_score:
            best_score = primary
            best_model = model_name.replace(":free", "")
        model_scores_list.append((model_name.replace(":free", ""), primary if isinstance(primary, (int, float)) else 0.0))

    success_rate = ((total_examples - total_errors) / max(total_examples, 1)) * 100

    # KPI Card 1: Top Performing Model
    _draw_kpi_card(ws, "B5", "C6", "🏆 TOP PERFORMING MODEL", best_model[:24])
    # KPI Card 2: Highest Primary Score
    _draw_kpi_card(ws, "D5", "E6", "🎯 BEST SCORE", f"{best_score:.4f}" if best_score >= 0 else "N/A")
    # KPI Card 3: Reliability
    _draw_kpi_card(ws, "F5", "G6", "⚡ API SUCCESS RATE", f"{success_rate:.1f}%")
    # KPI Card 4: Total Samples
    _draw_kpi_card(ws, "H5", "I6", "📊 TOTAL SAMPLES", str(total_examples))

    # Add embedded Bar Chart comparing primary metrics
    if len(model_scores_list) > 0:
        # Write small summary table to drive chart
        ws["B9"] = "Model"
        ws["C9"] = "Primary Score"
        ws["B9"].font = FONT_HEADER
        ws["B9"].fill = FILL_HEADER
        ws["C9"].font = FONT_HEADER
        ws["C9"].fill = FILL_HEADER

        for i, (m_name, m_score) in enumerate(model_scores_list):
            r = 10 + i
            ws[f"B{r}"] = m_name
            ws[f"C{r}"] = round(m_score, 4)
            ws[f"B{r}"].font = FONT_BODY
            ws[f"C{r}"].font = FONT_BOLD
            ws[f"B{r}"].border = BOX_BORDER
            ws[f"C{r}"].border = BOX_BORDER

        chart = BarChart()
        chart.type = "col"
        chart.style = 10
        chart.title = f"Comparative Primary Metric Profile ({task_name})"
        chart.y_axis.title = "Score (0.0 - 1.0)"
        chart.x_axis.title = "Model"
        chart.height = 10
        chart.width = 16

        data = Reference(ws, min_col=3, min_row=9, max_row=9 + len(model_scores_list))
        cats = Reference(ws, min_col=2, min_row=10, max_row=9 + len(model_scores_list))
        chart.add_data(data, titles_from_data=True)
        chart.set_categories(cats)
        chart.legend = None

        ws.add_chart(chart, "E9")

    # Set column widths
    for col_l in ["B", "C", "D", "E", "F", "G", "H", "I"]:
        ws.column_dimensions[col_l].width = 16


def _draw_kpi_card(ws, top_left: str, bottom_right: str, label: str, value: str):
    """Draw a rounded-style KPI stat box."""
    ws.merge_cells(f"{top_left}:{bottom_right}")
    tl_cell = ws[top_left]
    tl_cell.value = f"{label}\n{value}"
    tl_cell.font = FONT_KPI_VAL
    tl_cell.fill = FILL_CARD
    tl_cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    # Apply border across merged range
    from openpyxl.utils.cell import range_boundaries
    min_col, min_row, max_col, max_row = range_boundaries(f"{top_left}:{bottom_right}")
    for r in range(min_row, max_row + 1):
        for c in range(min_col, max_col + 1):
            ws.cell(row=r, column=c).border = BOX_BORDER
            ws.cell(row=r, column=c).fill = FILL_CARD
